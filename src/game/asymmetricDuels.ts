import type { ScenarioData } from './maps';
import type { PlayerId, TerrainKind, UnitKind } from './types';

type Site = readonly [number, number, TerrainKind, PlayerId?];
type Troop = readonly [UnitKind, number, number];
type Duel = Omit<ScenarioData, 'board' | 'initialUnits' | 'productionRules' | 'startingGold' | 'victoryConditions' | 'defeatConditions'> & {
  english: readonly [string, string];
  terrain: string[];
  properties: Site[];
  red: Troop[];
  blue: Troop[];
  victoryConditions?: ScenarioData['victoryConditions'];
  defeatConditions?: ScenarioData['defeatConditions'];
};

const terrainKinds: Record<string, TerrainKind> = { '.': 'plain', '+': 'forest', '#': 'mountain', '~': 'swamp', '=': 'road', w: 'sea' };
const standard = [{ type: 'eliminate' }, { type: 'captureCapital' }] as const;

function defineDuel({ english, terrain, properties, red, blue, ...duel }: Duel) {
  const width = terrain[0]!.length;
  const cells = new Map<string, Site>();
  for (const [y, row] of terrain.entries()) {
    if (row.length !== width) throw Error(duel.id + ': inconsistent row width');
    for (const [x, glyph] of Array.from(row).entries()) {
      const kind = terrainKinds[glyph];
      if (!kind) throw Error(duel.id + ': unknown terrain');
      if (kind !== 'plain') cells.set(x + ',' + y, [x, y, kind]);
    }
  }
  for (const site of properties) cells.set(site[0] + ',' + site[1], site);
  const troops = (owner: PlayerId, units: Troop[]) => units.map(([kind, x, y]) => ({ owner, kind, x, y }));
  const data: ScenarioData = {
    startingGold: 6000,
    productionRules: 'facility-v2',
    victoryConditions: standard,
    defeatConditions: standard,
    ...duel,
    board: { width, height: terrain.length, cells: [...cells.values()] },
    initialUnits: [...troops('red', red), ...troops('blue', blue)],
  };
  return { data, english };
}

